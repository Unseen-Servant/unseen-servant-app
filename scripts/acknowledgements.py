#!/usr/bin/env python3
"""Write ACKNOWLEDGEMENTS.txt: every third-party component the app ships,
with the licence texts their licences ask to travel with each copy.

Run from the repo root under the sidecar's environment, so the Python
packages it reads are the ones PyInstaller bundles:

    uv run --frozen --project sidecar --group build python scripts/acknowledgements.py

Each ecosystem is read where the build reads it:
- Rust crates: the normal-dependency closure of src-tauri in `cargo metadata`,
  across every target platform (a superset of any one build).
- JavaScript packages: the package-lock.json closure of package.json's
  dependencies, plus Svelte and SvelteKit, whose runtime the bundle carries
  although they are devDependencies.
- Python packages: the sidecar's runtime closure from `uv export`, as
  installed on this platform, plus PyInstaller, whose bootloader ships, and
  the interpreter itself.
- Models: the credit line of each entry in models/manifest.json, the files
  tauri build bundles.
- llama.cpp: the tag scripts/build-llama-server.sh pins, with the licence
  texts it leaves in src-tauri/binaries/llama-server-licenses (llama.cpp's
  and the code it vendors), so run that script first.

release.yml runs it on each platform before `tauri build`, so a release
lists that platform's Python packages (pywin32 only on Windows). The
committed copy is regenerated by hand when dependencies change.
"""
import hashlib
import json
import re
import subprocess
import sys
from importlib import metadata
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "ACKNOWLEDGEMENTS.txt"

LICENCE_FILE = re.compile(
    r"^(licen[cs]e|copying|notice|unlicense|copyright|third.?party.?notices)([-._].*)?$",
    re.IGNORECASE,
)
JS_RUNTIME_DEV_DEPS = ("svelte", "@sveltejs/kit")
FONT_AWESOME = (
    "Font Awesome Free 7 icons, by Fonticons, Inc. "
    "CC BY 4.0, https://fontawesome.com/license/free"
)
MCP_LOGO = (
    "Model Context Protocol logo, by the MCP project. MIT, "
    "https://commons.wikimedia.org/wiki/File:Model_Context_Protocol_logo.svg"
)


def models() -> list[str]:
    manifest = json.loads((ROOT / "models" / "manifest.json").read_text(encoding="utf-8"))
    return [f"  {m['credit']}" for m in manifest["models"]]


def llama_server():
    tag = re.search(r"^LLAMA_CPP_TAG=(\S+)", (ROOT / "scripts" / "build-llama-server.sh").read_text(), re.M)
    licences = ROOT / "src-tauri" / "binaries" / "llama-server-licenses"
    files = sorted(licences.iterdir()) if licences.is_dir() else []
    return "llama.cpp (llama-server)", tag.group(1), "MIT", files


def licence_files(directory: Path) -> list[Path]:
    if not directory.is_dir():
        return []
    return [f for f in sorted(directory.iterdir()) if f.is_file() and LICENCE_FILE.match(f.name)]


def rust_crates():
    out = subprocess.run(
        ["cargo", "metadata", "--format-version", "1", "--locked",
         "--manifest-path", str(ROOT / "src-tauri" / "Cargo.toml")],
        check=True, capture_output=True, text=True, encoding="utf-8",
    ).stdout
    meta = json.loads(out)
    packages = {p["id"]: p for p in meta["packages"]}
    nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
    seen: set[str] = set()
    stack = [meta["resolve"]["root"]]
    while stack:
        for dep in nodes[stack.pop()]["deps"]:
            # Build-script and dev dependencies run at compile time only.
            normal = any(k["kind"] is None for k in dep["dep_kinds"])
            if normal and dep["pkg"] not in seen:
                seen.add(dep["pkg"])
                stack.append(dep["pkg"])
    for pid in seen:
        p = packages[pid]
        crate_dir = Path(p["manifest_path"]).parent
        files = licence_files(crate_dir)
        if p.get("license_file"):
            files.insert(0, crate_dir / p["license_file"])
        yield p["name"], p["version"], p.get("license") or "", files


def js_packages():
    lock = json.loads((ROOT / "package-lock.json").read_text(encoding="utf-8"))["packages"]
    manifest = json.loads((ROOT / "package.json").read_text(encoding="utf-8"))

    def resolve(parent: str, name: str) -> str | None:
        # Node's lookup: the nearest node_modules up from the dependent.
        base = parent
        while True:
            key = f"{base}/node_modules/{name}" if base else f"node_modules/{name}"
            if key in lock:
                return key
            if not base:
                return None
            base = base.rsplit("/node_modules/", 1)[0] if "/node_modules/" in base else ""

    seen: set[str] = set()
    stack = [k for k in (resolve("", n) for n in [*manifest.get("dependencies", {}), *JS_RUNTIME_DEV_DEPS]) if k]
    while stack:
        key = stack.pop()
        if key in seen or not (ROOT / key).is_dir():
            continue
        seen.add(key)
        entry = lock[key]
        for name in [*entry.get("dependencies", {}), *entry.get("optionalDependencies", {})]:
            dep = resolve(key, name)
            if dep:
                stack.append(dep)
    for key in seen:
        entry = lock[key]
        name = key.rsplit("node_modules/", 1)[1]
        yield name, entry.get("version", ""), entry.get("license", ""), licence_files(ROOT / key)


def python_packages():
    out = subprocess.run(
        ["uv", "export", "--frozen", "--no-dev", "--no-hashes", "--no-emit-project",
         "--project", str(ROOT / "sidecar")],
        check=True, capture_output=True, text=True, encoding="utf-8",
    ).stdout
    names = [line.split("==")[0] for line in out.splitlines() if "==" in line and not line.startswith("#")]
    for name in [*names, "pyinstaller"]:
        try:
            dist = metadata.distribution(name)
        except metadata.PackageNotFoundError:
            continue  # another platform's package: not in this build
        files = []
        for f in dist.files or []:
            in_dist_info = f.parts[0].endswith(".dist-info")
            if LICENCE_FILE.match(f.name) and (in_dist_info or len(f.parts) <= 2):
                files.append(Path(dist.locate_file(f)))
        expr = dist.metadata.get("License-Expression") or ""
        if not expr:
            licence = dist.metadata.get("License") or ""
            classifiers = [c.rsplit(" :: ", 1)[1] for c in dist.metadata.get_all("Classifier") or []
                           if c.startswith("License ::")]
            expr = licence if 0 < len(licence) < 80 else " / ".join(classifiers)
        yield dist.metadata["Name"], dist.version, expr, files


def python_interpreter():
    version = ".".join(map(str, sys.version_info[:3]))
    base = Path(sys.base_prefix)
    candidates = [base / "LICENSE.txt", base / "lib" / f"python{sys.version_info[0]}.{sys.version_info[1]}" / "LICENSE.txt"]
    return "Python", version, "PSF-2.0", [p for p in candidates if p.is_file()][:1]


def main() -> None:
    texts: dict[str, int] = {}
    bodies: list[tuple[str, list[str]]] = []

    def refs(component: str, files: list[Path]) -> str:
        nums = []
        for path in dict.fromkeys(files):
            body = path.read_text(encoding="utf-8", errors="replace").strip()
            digest = hashlib.sha256(body.encode()).hexdigest()
            if digest not in texts:
                texts[digest] = len(bodies) + 1
                bodies.append((body, []))
            num = texts[digest]
            if component not in bodies[num - 1][1]:
                bodies[num - 1][1].append(component)
            nums.append(num)
        return f"[{', '.join(map(str, sorted(set(nums))))}]" if nums else "[no licence file in the package]"

    def section(title: str, components) -> list[str]:
        lines = [title, ""]
        for name, version, expr, files in sorted(components, key=lambda c: (c[0].lower(), c[1])):
            label = f"{name} {version}".strip()
            lines.append(f"  {label}  {expr or 'licence not declared'}  {refs(label, files)}")
        return [*lines, ""]

    fonts = ROOT / "static" / "fonts" / "OFL.txt"
    lines = [
        "ACKNOWLEDGEMENTS",
        "",
        "Unseen Servant is free software under the GNU Affero General Public",
        "License v3.0 or later (see LICENSE). It is built on the work of the",
        "projects below. Each is listed with its licence and the numbers of the",
        "licence texts, which follow the lists.",
        "",
        "Generated by scripts/acknowledgements.py. Don't edit by hand.",
        "",
        "Fonts and icons",
        "",
        f"  Crimson Text  OFL-1.1  {refs('Crimson Text', [fonts])}",
        f"  Almendra  OFL-1.1  {refs('Almendra', [fonts])}",
        f"  IBM Plex Mono  OFL-1.1  {refs('IBM Plex Mono', [fonts])}",
        f"  {FONT_AWESOME}",
        f"  {MCP_LOGO}",
        "",
        "Models",
        "",
        *models(),
        "",
        *section("Bundled Python interpreter", [python_interpreter()]),
        *section("Rust crates (the app)", rust_crates()),
        *section("JavaScript packages (the interface)", js_packages()),
        *section("Python packages (the indexing sidecar)", python_packages()),
        *section("Bundled embedding server", [llama_server()]),
        "Licence texts",
        "",
    ]
    for num, (body, users) in enumerate(bodies, start=1):
        lines += ["=" * 78, f"[{num}] Used by: {', '.join(users)}", "=" * 78, "", body, ""]
    OUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"Wrote {OUT.relative_to(ROOT)}: {len(bodies)} licence texts, {OUT.stat().st_size // 1024} KB")


if __name__ == "__main__":
    main()
